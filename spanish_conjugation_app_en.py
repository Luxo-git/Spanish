    def _set_translation_tense_filter(self, value):
        self.translation_tense_filter = value
        self._refresh_translation_tense_buttons()

    def _refresh_translation_tense_buttons(self):
        for value, btn in self.translation_tense_buttons.items():
            active = value == self.translation_tense_filter
            color = TENSE_COLORS[value] if value else COL_BROWN_DARK
            if active:
                btn.config(bg=color, fg="white")
            else:
                btn.config(bg="#FFFFFF", fg=COL_BROWN_DARK)

    def new_sentence(self):
        self.translation_reviewing = False
        self.translation_result_label.config(text="")

        self.translation_tense = (
            self.translation_tense_filter if self.translation_tense_filter is not None
            else random.choice(TENSES)
        )
        en, es = random.choice(TRANSLATION_SENTENCES[self.translation_tense])
        self.translation_sentence_en = en
        self.translation_sentence_es = es

        for w in self.translation_card.winfo_children():
            w.destroy()

        tk.Label(
            self.translation_card,
            text=f"{TENSE_EMOJI[self.translation_tense]} Tense requested: {self.translation_tense}",
            font=(FONT_FAMILY, 11, "italic"), bg=BG_CARD, fg=COL_MUTED
        ).pack(pady=(24, 10))

        tk.Label(
            self.translation_card, text=self.translation_sentence_en, font=(FONT_FAMILY, 19, "bold"),
            bg=BG_CARD, fg=COL_TEXT, wraplength=680, justify="center"
        ).pack(pady=(0, 20), padx=20)

        self.translation_entry = ttk.Entry(
            self.translation_card, font=(FONT_FAMILY, 15), width=50, justify="center"
        )
        self.translation_entry.pack(pady=6, ipady=6)
        self.translation_entry.focus_set()

    def _grade_translation(self):
        self.translation_reviewing = True
        self.total_translation += 1

        answer = self.translation_entry.get()
        ok = normalize_sentence(answer) == normalize_sentence(self.translation_sentence_es)
        self.translation_entry.config(state="disabled")

        if ok:
            self.score_translation += 1
            msg = random.choice(CORRECT_MESSAGES)
            self.translation_result_label.config(text=msg, fg=COL_OK)
        else:
            msg = random.choice(WRONG_MESSAGES)
            self.translation_result_label.config(
                text=f"{msg} Expected translation: {self.translation_sentence_es}", fg=COL_KO
            )

        self.score_translation_label.config(
            text=f"🏆 Score: {self.score_translation}/{self.total_translation}"
        )
        self.translation_submit_btn.config(text="▶ Next sentence  (Enter)")


