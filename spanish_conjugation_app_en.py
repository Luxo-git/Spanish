def regular_conjugation(verb, tense):
    group = verb[-2:]
    stem = verb[:-2]
    return [stem + ending for ending in REGULAR_ENDINGS[tense][group]]


def get_conjugation(verb, tense):
    if verb in IRREGULAR_VERBS and tense in IRREGULAR_VERBS[verb]:
        return IRREGULAR_VERBS[verb][tense]
    return regular_conjugation(verb, tense)


def normalize(text):
    text = text.strip().lower()
    text = unicodedata.normalize("NFKD", text)
    return "".join(c for c in text if not unicodedata.combining(c))


def normalize_sentence(text):
    """Lenient comparison for full sentences: accents, case, punctuation
    and repeated spaces are all ignored."""
    text = normalize(text)
    text = re.sub(r"[¿¡?!.,;:]", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


