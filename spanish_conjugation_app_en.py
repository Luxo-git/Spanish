    def new_question(self):
        self._stop_timer()
        self.reviewing_answer = False
        self.result_label.config(text="")

        self.verb = random.choice(ALL_VERBS)
        self.tense = self.tense_filter if self.tense_filter is not None else random.choice(TENSES)

        self.all_persons_mode = self.all_persons_on

        conjugations = get_conjugation(self.verb, self.tense)
        if self.all_persons_mode:
            self.correct_answer = conjugations
            self.pronoun_idx = None
        else:
            self.pronoun_idx = random.randint(0, 5)
            self.correct_answer = conjugations[self.pronoun_idx]

        self._update_header()
        self._render_question()
        self._start_timer()

