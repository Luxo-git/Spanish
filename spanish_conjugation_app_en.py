    # ------------------------------------------------------------------
    # Timer
    # ------------------------------------------------------------------

    def _start_timer(self):
        self.time_left = DURATION_QUESTION
        self._update_timer_label()
        self._tick()

    def _tick(self):
        if self.time_left <= 0:
            self._on_timeout()
            return
        self._update_timer_label()
        self.time_left -= 1
        self.timer_id = self.after(1000, self._tick)

    def _update_timer_label(self):
        self.timer_label.config(text=f"{self.time_left}s")
        self.timer_label.config(fg="#F3C6B0" if self.time_left <= 10 else "white")

    def _stop_timer(self):
        if self.timer_id is not None:
            self.after_cancel(self.timer_id)
            self.timer_id = None

    def _on_timeout(self):
        self._stop_timer()
        self._grade(timeout=True)

    # ------------------------------------------------------------------
    # Answer submission / grading
