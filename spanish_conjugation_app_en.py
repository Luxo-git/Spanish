    def _on_enter(self):
        if self.current_page is self.game_frame:
            if self.reviewing_answer:
                self.new_question()
            else:
                self._stop_timer()
                self._grade(timeout=False)
        elif self.current_page is self.translation_frame:
            if self.translation_reviewing:
                self.new_sentence()
            else:
                self._grade_translation()

    def _grade(self, timeout):
        self.reviewing_answer = True
        self.total += 1

        if self.all_persons_mode:
            nb_correct = 0
            for i, entry in enumerate(self.entries):
                value = "" if timeout else entry.get()
                correct = self.correct_answer[i]
                ok = normalize(value) == normalize(correct)
                entry.config(state="disabled")
                if ok:
                    nb_correct += 1
                    self.feedback_labels[i].config(text=f"✅ {correct}", fg=COL_OK)
                else:
                    self.feedback_labels[i].config(text=f"❌ {correct}", fg=COL_KO)

            perfect = nb_correct == 6
            if perfect:
                self.score += 1
                self.streak += 1
                self.best_streak = max(self.best_streak, self.streak)
                msg = random.choice(CORRECT_MESSAGES)
                self.result_label.config(text=f"{msg} All 6 forms are correct!", fg=COL_OK)
            else:
                self.streak = 0
                msg = random.choice(TIMEOUT_MESSAGES if timeout else WRONG_MESSAGES)
                self.result_label.config(text=f"{msg} ({nb_correct}/6 forms correct)", fg=COL_KO)
        else:
            entry = self.entries[0]
            value = "" if timeout else entry.get()
            ok = normalize(value) == normalize(self.correct_answer)
            entry.config(state="disabled")
            if ok:
                self.score += 1
                self.streak += 1
                self.best_streak = max(self.best_streak, self.streak)
                msg = random.choice(CORRECT_MESSAGES)
                self.result_label.config(text=msg, fg=COL_OK)
            else:
                self.streak = 0
                msg = random.choice(TIMEOUT_MESSAGES if timeout else WRONG_MESSAGES)
                self.result_label.config(
                    text=f"{msg} The correct answer was: {self.correct_answer}", fg=COL_KO
                )

        self.score_label.config(text=f"🏆 Score: {self.score}/{self.total}")
        self.streak_label.config(text=f"🔥 Streak: {self.streak}" if self.streak >= 2 else "")
        self.submit_btn.config(text="▶ Next question  (Enter)")

    def quit_app(self):
        self._stop_timer()
        recap = []
        if self.total > 0:
            percentage = 100 * self.score / self.total
            recap.append(
                f"🎮 Conjugation Game: {self.score}/{self.total} ({percentage:.0f}%) "
                f"— best streak {self.best_streak} 🔥"
            )
        if self.total_translation > 0:
            percentage_tr = 100 * self.score_translation / self.total_translation
            recap.append(
                f"🗣️ Translation: {self.score_translation}/{self.total_translation} ({percentage_tr:.0f}%)"
            )
        if recap:
            messagebox.showinfo("Session complete", "\n\n".join(recap))
        self.destroy()

